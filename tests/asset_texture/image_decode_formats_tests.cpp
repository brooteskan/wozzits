// tests/asset_texture/image_decode_formats_tests.cpp
//
// Proves the engine can actually decode the formats real assets arrive as.
//
// This is a CODEC-COVERAGE test, not a correctness test of stb. The gap it
// closes: stb_image is compiled into image_decode.cpp with an STBI_NO_* opt-out
// per format, and those macros are a live lever -- they are the documented way
// to shrink the binary, and dropping a codec is a one-line edit. Before this
// file, the only coverage of decode_image_rgba8 was image_decode_limits_tests,
// whose every fixture is a hand-built uncompressed TGA (chosen so a tiny file
// can claim enormous dimensions). So `#define STBI_NO_PNG` would have left the
// entire suite green while every project on disk silently stopped loading
// textures, because nothing anywhere decoded a real compressed image.
//
// PNG and JPEG specifically because those are what the two callers are fed:
// texture assets carry a RawFile dependency's bytes (texture_compilers.cpp) and
// Inochi puppets carry embedded texture blobs (inochi_load.cpp). Neither looks
// at a file extension -- stb sniffs the content -- so a missing codec surfaces
// only as a decode failure at load time.
//
// The fixtures are real encoder output embedded as bytes rather than files on
// disk: the test needs no fixture path, no I/O, and cannot be broken by the
// working directory.

